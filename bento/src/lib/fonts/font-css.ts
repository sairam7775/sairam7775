import { readFileSync } from "node:fs";
import { join } from "node:path";

/* Builds src/app/fonts.css, the app's one font stylesheet, from the
   fontsource packages (`npm run fonts`; font-css.test.ts fails while the
   file is stale). Nothing is fetched: the faces point at the woff2 files in
   node_modules, which the build copies like any other asset.

   Why not import fontsource's own files: each weight's file declares ~120
   faces (the Japanese glyphs split by unicode-range, so a page downloads only
   the slices it uses), and five Zen weights repeat the same ranges. Apart,
   they were five render-blocking stylesheets of ~33 KB gzipped each. Here
   the Japanese faces of all weights are interleaved slice by slice, so the
   repeated ranges sit side by side and compress to almost one weight's
   cost; the woff fallback is dropped (every browser that reads
   unicode-range reads woff2). Each weight keeps every face and the order
   fontsource gives it, so the same character comes from the same file. */

/** The weights the app uses (DESIGN.md → Typography). Any other weight
 *  shows as the nearest loaded one: font-semibold (600) as 700, and
 *  font-extrabold (800) as 900 in Maru but 700 in Kaku. */
export const FONTS = [
  { pkg: "zen-maru-gothic", weights: [700, 900] }, // headlines
  { pkg: "zen-kaku-gothic-new", weights: [400, 500, 700] }, // body
  { pkg: "dm-mono", weights: [400, 500] }, // data
] as const;

/** Symbols the interface writes (back and forward arrows, ↗, ✓) that the Zen
 *  fonts carry only in their Japanese slices. Left there, one "←" in a back
 *  link downloaded a ~10 KB file of kanji on pages with no Japanese, so they
 *  are drawn by the system font, as ↻, ↳ and ▾ already were. */
export const SYSTEM_SYMBOLS = [
  [0x2190, 0x21ff], // arrows
  [0x2713, 0x2714], // check marks
] as const;

export type Face = {
  pkg: string;
  family: string;
  style: string;
  weight: number;
  file: string;
  ranges: [number, number][];
};

const HEADER = `/* Generated by scripts/build-fonts.ts from src/lib/fonts/font-css.ts.
   Don't edit: change font-css.ts and run \`npm run fonts\`. */
`;

export function readFontsource(pkg: string, weight: number): string {
  return readFileSync(join(process.cwd(), "node_modules", "@fontsource", pkg, `${weight}.css`), "utf8");
}

const hex = (n: number) => n.toString(16);

function parseRanges(text: string | undefined): [number, number][] {
  if (!text) return [[0, 0x10ffff]];
  return text.split(",").map((part) => {
    const [a, b] = part.trim().replace(/^U\+/i, "").split("-");
    return [parseInt(a, 16), parseInt(b ?? a, 16)];
  });
}

/** The faces of a fontsource stylesheet, or of fonts.css itself. */
export function parseFaces(css: string): Face[] {
  return [...css.matchAll(/@font-face\s*\{([^}]*)\}/g)].map(([, body]) => {
    const get = (prop: string) => body.match(new RegExp(`${prop}:\\s*([^;]+)`))?.[1].trim();
    const url = body.match(/url\(([^)]*?\.woff2)\)/)?.[1] ?? "";
    const ours = url.match(/@fontsource\/([^/]+)\/files\/([^/]+)$/);
    const file = ours ? ours[2] : url.replace(/^\.\/files\//, "");
    const family = (get("font-family") ?? "").replace(/^['"]|['"]$/g, "");
    return {
      pkg: ours ? ours[1] : pkgOf(file),
      family,
      style: get("font-style") ?? "normal",
      weight: Number(get("font-weight")),
      file,
      ranges: parseRanges(get("unicode-range")),
    };
  });
}

function pkgOf(file: string): string {
  return FONTS.map((f) => f.pkg as string).find((p) => file.startsWith(`${p}-`)) ?? "";
}

/** A Japanese slice: fontsource names them by number, e.g. "-118-400-normal". */
const sliceOf = (face: Face) => face.file.match(/-(\d+)-\d+-normal\.woff2$/)?.[1];

function withoutSymbols(ranges: [number, number][]): [number, number][] {
  let parts = ranges;
  for (const [x, y] of SYSTEM_SYMBOLS) {
    parts = parts.flatMap(([a, b]): [number, number][] => {
      if (y < a || x > b) return [[a, b]];
      const left: [number, number][] = a < x ? [[a, x - 1]] : [];
      const right: [number, number][] = b > y ? [[y + 1, b]] : [];
      return [...left, ...right];
    });
  }
  return parts;
}

function render(face: Face): string {
  const range = face.ranges.map(([a, b]) => (a === b ? `U+${hex(a)}` : `U+${hex(a)}-${hex(b)}`)).join(",");
  return `@font-face{font-family:'${face.family}';font-style:${face.style};font-display:swap;font-weight:${face.weight};` +
    `src:url(../../node_modules/@fontsource/${face.pkg}/files/${face.file}) format('woff2');unicode-range:${range}}`;
}

export function buildFontCss(read: (pkg: string, weight: number) => string): string {
  const weights = FONTS.flatMap(({ pkg, weights }) =>
    weights.map((weight) => parseFaces(read(pkg, weight)).map((face) => ({ ...face, pkg }))),
  );
  const japanese = new Map<number, Face[]>();
  const named: Face[] = [];
  for (const faces of weights) {
    for (const face of faces) {
      const slice = sliceOf(face);
      if (slice === undefined) {
        named.push(face);
        continue;
      }
      const ranges = withoutSymbols(face.ranges);
      if (ranges.length === 0) continue;
      const n = Number(slice);
      japanese.set(n, [...(japanese.get(n) ?? []), { ...face, ranges }]);
    }
  }
  // Japanese slices first, as in fontsource, so the Latin faces after them
  // win any character both cover.
  const ordered = [...[...japanese.keys()].sort((a, b) => a - b).flatMap((n) => japanese.get(n)!), ...named];
  return HEADER + ordered.map(render).join("\n") + "\n";
}
